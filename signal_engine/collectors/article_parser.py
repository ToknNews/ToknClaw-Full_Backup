import requests
from bs4 import BeautifulSoup


def extract_summary(url):

    try:
        response = requests.get(url, timeout=8)

        soup = BeautifulSoup(response.text, "lxml")

        paragraphs = soup.find_all("p")

        text = " ".join([p.get_text() for p in paragraphs[:4]])

        return text[:500]

    except Exception:
        return ""
